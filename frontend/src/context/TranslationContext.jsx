const TranslationContext = createContext(null);

export function TranslationProvider({ children }) {
  const { user } = useAuth();
  const savedLang = localStorage.getItem("igym_lang") || "fr";
  const [lang, setLang] = useState(savedLang);

  // Sync lang with database user preference when user loads
  useEffect(() => {
    if (user && user.language_preference && user.language_preference !== lang) {
      if (translations[user.language_preference]) {
        setLang(user.language_preference);
        localStorage.setItem("igym_lang", user.language_preference);
      }
    }
  }, [user]);

  const changeLanguage = useCallback(
    async (newLang) => {
      if (translations[newLang]) {
        setLang(newLang);
        localStorage.setItem("igym_lang", newLang);

        // If user is authenticated, save preference to the database
        if (user) {
          try {
            await api.put("/user/profile", {
              name: user.name,
              email: user.email,
              language_preference: newLang,
            });
            // Update user object locally in AuthContext
            user.language_preference = newLang;
          } catch (e) {
            console.error("Failed to persist language preference", e);
          }
        }
      }
    },
    [user, lang],
  );

  useEffect(() => {
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key, params = {}) => {
      let str =
        (translations[lang] && translations[lang][key]) ||
        (translations["fr"] && translations["fr"][key]) ||
        key;
      if (params && typeof params === "object") {
        Object.entries(params).forEach(([k, v]) => {
          str = str.replace(`{${k}}`, v);
        });
      }
      return str;
    },
    [lang],
  );

  return (
    <TranslationContext.Provider
      value={{
        lang,
        changeLanguage,
        t,
        availableLanguages: Object.keys(translations),
      }}
    >
      <div dir={lang === "ar" ? "rtl" : "ltr"}>{children}</div>
    </TranslationContext.Provider>
  );
}

export function useTranslation() {
  const ctx = useContext(TranslationContext);
  if (!ctx)
    throw new Error("useTranslation must be used within TranslationProvider");
  return ctx;
}
